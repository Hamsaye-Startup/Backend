package com.microservices.reservation.warehouse.models;

/**
 * This enum represents the confirmation status of a reservation.
 * It indicates whether a reservation has been confirmed or not.
 *
 * @author Pouria Ghafarbeigi
 * @version 1.0
 */
public enum ConfirmReserveEnum {
    /**
     * Indicates that the reservation is not confirmed.
     */
    NOT_CONFIRMED,

    /**
     * Indicates that the reservation has been confirmed.
     */
    CONFIRMED
}
