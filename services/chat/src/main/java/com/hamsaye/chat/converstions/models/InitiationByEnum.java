package com.hamsaye.chat.converstions.models;

/**
 * Enumeration representing the different ways a conversation can be initiated.
 * Currently, it supports a single value indicating that the conversation was initiated by the user.
 *
 * @author Pouria Ghafarbeigi
 * @version 1.0
 */
public enum InitiationByEnum {
    /**
     * Indicates that the conversation was initiated by the user.
     */
    USER_INITIATED
}
